import { readFile, writeFile } from "node:fs/promises";
import path from "node:path";

import { get } from "admdongkor";

const VERSION = process.env.LOCATION_DATA_VERSION ?? "20260701";
const OUTPUT_PATH = path.resolve("lib/data/korean-locations.ts");
const PARQUET_DIR = process.env.LOCATION_PARQUET_DIR;
const LEVELS = ["sido", "sgg", "emd"];

function getCenter(geometry) {
  let minLongitude = Infinity;
  let maxLongitude = -Infinity;
  let minLatitude = Infinity;
  let maxLatitude = -Infinity;

  function visit(coordinates) {
    if (
      Array.isArray(coordinates) &&
      typeof coordinates[0] === "number" &&
      typeof coordinates[1] === "number"
    ) {
      minLongitude = Math.min(minLongitude, coordinates[0]);
      maxLongitude = Math.max(maxLongitude, coordinates[0]);
      minLatitude = Math.min(minLatitude, coordinates[1]);
      maxLatitude = Math.max(maxLatitude, coordinates[1]);
      return;
    }

    for (const child of coordinates) visit(child);
  }

  visit(geometry.coordinates);
  return {
    latitude: (minLatitude + maxLatitude) / 2,
    longitude: (minLongitude + maxLongitude) / 2,
  };
}

function getCode(level, properties) {
  if (level === "sido") return properties.sidocd;
  if (level === "sgg") return properties.sggcd;
  return properties.emdcd;
}

function getName(level, properties) {
  if (level === "sido") return properties.sidonm;
  if (level === "sgg") return properties.sggnm;
  return properties.emdnm;
}

function formatSggName(name) {
  return name.replace(/시(?=[가-힣]+구$)/, "시 ");
}

function getLabel(level, properties) {
  if (level === "sido") return properties.sidonm;
  if (level === "sgg") return `${properties.sidonm} ${formatSggName(properties.sggnm)}`;
  return `${properties.sidonm} ${formatSggName(properties.sggnm)} ${properties.emdnm}`;
}

async function localFetch(url) {
  if (!PARQUET_DIR) return fetch(url);
  const filename = new URL(url).pathname.split("/").at(-1);
  const bytes = await readFile(path.join(PARQUET_DIR, filename));
  return new Response(bytes);
}

const rows = [];
for (const level of LEVELS) {
  const collection = await get(VERSION, level, { fetch: localFetch });
  for (const feature of collection.features) {
    const code = getCode(level, feature.properties);
    if (!code) continue;
    const center = getCenter(feature.geometry);
    rows.push([
      level,
      code,
      getLabel(level, feature.properties),
      getName(level, feature.properties),
      Number(center.latitude.toFixed(4)),
      Number(center.longitude.toFixed(4)),
      Math.round((center.longitude - 135) * 4),
    ]);
  }
}

rows.sort((left, right) => left[2].localeCompare(right[2], "ko"));

const output = `// Generated by scripts/generate-korean-locations.mjs. Do not edit manually.\n` +
  `// Source: admdongkor ${VERSION}, WGS84 administrative-boundary centers.\n` +
  `export type KoreanLocationLevel = "sido" | "sgg" | "emd";\n\n` +
  `export type KoreanLocationRow = readonly [\n` +
  `  level: KoreanLocationLevel,\n` +
  `  code: string,\n` +
  `  label: string,\n` +
  `  name: string,\n` +
  `  latitude: number,\n` +
  `  longitude: number,\n` +
  `  correctionMinutes: number,\n` +
  `];\n\n` +
  `export const KOREAN_LOCATION_DATA_VERSION = ${JSON.stringify(VERSION)};\n\n` +
  `export const KOREAN_LOCATION_ROWS: readonly KoreanLocationRow[] = [\n  ${rows.map((row) => JSON.stringify(row)).join(",\n  ")}\n];\n`;

await writeFile(OUTPUT_PATH, output);
console.log(`Generated ${rows.length} locations at ${OUTPUT_PATH}`);
