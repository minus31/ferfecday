function getTenGod(dayStem: string, targetStem: string): TenGod {
  const day = STEM_META[dayStem];
  const target = STEM_META[targetStem];
  const samePolarity = day.polarity === target.polarity;
  if (day.element === target.element) return samePolarity ? "비견" : "겁재";
  if (ELEMENT_GENERATES[day.element] === target.element) return samePolarity ? "식신" : "상관";
  if (ELEMENT_GENERATES[target.element] === day.element) return samePolarity ? "편인" : "정인";
  if (ELEMENT_CONTROLS[day.element] === target.element) return samePolarity ? "편재" : "정재";
  return samePolarity ? "편관" : "정관";
}

function getTwelveStage(dayStem: string, dayBranch: string): TwelveStage {
  const index = STAGE_BRANCH_ORDER[dayStem].indexOf(dayBranch);
  return TWELVE_STAGE_ORDER[index];
}

function getNotablePatterns(ganzi: DayPillar) {
  return PATTERN_SETS.filter(({ pillars }) => pillars.includes(ganzi)).map(({ label }) => label);
}

function splitKeywords(value: string) {
  return value.split("·");
}

function getSourceUrl(ganzi: DayPillar) {
  const path = SOURCE_PATH_OVERRIDES[ganzi] ?? encodeURIComponent(`${HANGUL[ganzi]}일주`);
  return `https://sajuabc.com/${path}/`;
}

